"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs"), os = require("node:os"), path = require("node:path"), crypto = require("node:crypto");
const { AuthService } = require("../backend/auth-service");
const directory = fs.mkdtempSync(path.join(os.tmpdir(), "witt-migration-check-"));
let response, body;
const service = new AuthService({ dir: directory, migrationEnabled: true,
  sendJson(_res, status, data, headers) { response = { status, data, headers }; },
  readJsonBody(_req, _limit, callback) { callback(null, body); } });
const activate = (invite) => service.activate({ inviteCode: invite.code, deviceId: crypto.randomUUID(), deviceName: "fixture" });
try {
  assert.equal(service.migrationStatus(undefined), null);
  const admin = activate(service.initialize(crypto.randomBytes(20).toString("hex")));
  const source = activate(service.createInvite({ label: "legacy" }));
  const principal = service.authenticateToken(source.token);
  service.setUserPolicy(principal.userId, { codexProfiles: ["xuanyu"], unrestrictedModels: true });
  const offer = service.issueMigration(principal);
  assert.ok(!JSON.stringify(service.read()).includes(offer.code.split(".")[1]), "raw secret stored");
  const targetId = crypto.randomUUID();
  const input = { inviteCode: offer.code, deviceId: targetId, deviceName: "Osaka" };
  const result = service.activate(input);
  assert.equal(result.device.userId, principal.userId);
  assert.equal(result.device.admin, false);
  assert.equal(result.migration.status, "claimed");
  assert.equal(service.authenticateToken(source.token).deviceId, principal.deviceId, "source session lost");
  const targetPrincipal = service.authenticateToken(result.token);
  assert.deepEqual(targetPrincipal.codexProfiles, ["xuanyu"]);
  assert.equal(targetPrincipal.unrestrictedModels, true);
  assert.equal(service.activate(input).token, result.token, "same device retry failed");
  assert.throws(() => service.activate({ ...input, deviceId: crypto.randomUUID() }), /其他设备/);
  assert.doesNotThrow(() => service.recordMigrationAccess(null, "files"));
  service.recordMigrationAccess(principal, "conversations");
  assert.equal(service.migrationStatus(targetId).conversations, false, "source counted as target proof");
  service.recordMigrationAccess(targetPrincipal, "conversations");
  assert.equal(service.migrationStatus(targetId).status, "claimed");
  service.recordMigrationAccess(targetPrincipal, "files");
  assert.equal(service.migrationStatus(targetId).status, "confirmed");
  assert.equal(service.migrationStatus(principal.deviceId).role, "source");
  assert.ok(service.authenticateToken(source.token), "confirmation disabled original");
  assert.throws(() => service.issueMigration(principal, admin.device.id, "ownership-verified"), /核实/);
  const adminPrincipal = service.authenticateToken(admin.token);
  assert.throws(() => service.issueMigration(adminPrincipal, source.device.id, "self"), /归属/);
  const recovery = service.issueMigration(adminPrincipal, source.device.id, "ownership-verified");
  assert.throws(() => service.activate({ inviteCode: recovery.code, deviceId: admin.device.id }), /已有账号/);
  const snapshot = service.read();
  snapshot.migrationGrants.find((g) => recovery.code.includes(g.id)).expiresAt = new Date(0).toISOString();
  service.write(snapshot);
  assert.throws(() => service.activate({ inviteCode: recovery.code, deviceId: crypto.randomUUID() }), /过期/);
  const revoked = service.issueMigration(adminPrincipal, source.device.id, "ownership-verified");
  const pendingResult = service.activate({ inviteCode: revoked.code, deviceId: crypto.randomUUID() });
  const disabled = service.read(); disabled.devices.find((d) => d.id === source.device.id).disabled = true; service.write(disabled);
  assert.equal(service.authenticateToken(pendingResult.token), null, "unconfirmed migration bypassed source disable");
  assert.throws(() => service.issueMigration(adminPrincipal, source.device.id, "ownership-verified"), /禁用/);
  assert.throws(() => service.activate({ inviteCode: revoked.code, deviceId: crypto.randomUUID() }), /不可迁移/);
  assert.ok(service.authenticateToken(result.token), "confirmed independent target lost access");
  const other = activate(service.createInvite({ label: "other" }));
  const otherPrincipal = service.authenticateToken(other.token);
  service.handle({ method: "GET", headers: {} }, {}, { pathname: "/auth/status" }, otherPrincipal);
  assert.ok(response.data.migrationOffer);
  assert.equal(response.headers["Cache-Control"], "no-store");
  service.handle({ method: "GET", headers: {} }, {}, { pathname: "/auth/status" }, adminPrincipal);
  assert.equal(response.data.migrationOffer, null, "administrator received migration offer");
  service.handle({ method: "GET", headers: { "x-witt-client": "browser" } }, {}, { pathname: "/auth/status" }, otherPrincipal);
  assert.equal(response.data.migrationOffer, null, "browser received migration offer");
  body = { label: `WITT-RECOVERY:${other.device.id}:ownership-verified` };
  assert.equal(service.handle({ method: "POST", headers: {} }, {}, { pathname: "/admin/invites" }, otherPrincipal), false);
  const usersBefore = service.read().invites.length;
  service.handle({ method: "POST", headers: {} }, {}, { pathname: "/admin/invites" }, adminPrincipal);
  assert.equal(response.status, 201); assert.ok(response.data.migrationRecovery);
  assert.equal(service.read().invites.length, usersBefore, "recovery created blank account");
  const r = service.activate({ inviteCode: response.data.invite.code, deviceId: crypto.randomUUID() });
  assert.equal(r.device.userId, other.device.userId);
  assert.ok(!JSON.stringify(service.publicDevice(r.device)).includes(r.token));
  const open = activate(service.createInvite({ label: "开放版 fixture" }));
  const openPrincipal = service.authenticateToken(open.token);
  assert.throws(() => service.issueMigration(openPrincipal), /核实/);
  service.handle({ method: "GET", headers: {} }, {}, { pathname: "/auth/status" }, openPrincipal);
  assert.equal(response.data.migrationOffer, null, "open edition received migration offer");
  const retryOffer = service.issueMigration(otherPrincipal);
  const retryInput = { inviteCode: retryOffer.code, deviceId: crypto.randomUUID() };
  const originalWrite = service.write.bind(service);
  service.write = (data) => { originalWrite(data); throw new Error("simulated mirror/response failure"); };
  assert.throws(() => service.activate(retryInput), /simulated/);
  service.write = originalWrite;
  assert.ok(service.authenticateToken(service.activate(retryInput).token), "committed response failure could not retry");
  const closed = new AuthService({ dir: directory, sendJson(_res, status, data) { response = { status, data }; }, readJsonBody: service.readJsonBody });
  assert.throws(() => closed.issueMigration(otherPrincipal), /已关闭/);
  assert.throws(() => closed.activate(retryInput), /已关闭/);
  assert.ok(closed.authenticateToken(result.token), "closing broke completed migration session");
  closed.handle({ method: "GET", headers: {} }, {}, { pathname: "/auth/status" }, otherPrincipal);
  assert.equal(response.data.migrationSupported, false);
  assert.equal(response.data.migrationOffer, null);
  assert.equal(response.data.migration, null);
  const closedState = service.read(); closedState.migrationClosedAt = new Date().toISOString(); service.write(closedState);
  assert.throws(() => service.issueMigration(otherPrincipal), /已关闭/);
  assert.throws(() => service.activate(retryInput), /已关闭/);
  assert.ok(service.authenticateToken(result.token));
  closed.store.db.close();
  console.log("account migration and closure checks passed");
} finally { service.store.db.close(); fs.rmSync(directory, { recursive: true, force: true }); }
