'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const {AuthService}=require('../backend/auth-service');
const {ChatService}=require('../backend/chat-service');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'witt-all-models-'));
const auth=new AuthService({dir:path.join(root,'auth'),sendJson(){},readJsonBody(){}});
auth.initialize(crypto.randomBytes(24).toString('base64url'));
const invitation=auth.createInvite({label:'ordinary',admin:false});
const device=auth.activate({inviteCode:invitation.code,deviceId:crypto.randomUUID(),deviceName:'ordinary'});
let principal=auth.authenticateToken(device.token);
assert.equal(principal.unrestrictedModels,true);assert.equal(principal.admin,false);assert.equal(principal.fullServerAccess,false);
const store=auth.read();store.defaultUserPolicy={unrestrictedModels:true};auth.write(store);
principal=auth.authenticateToken(device.token);assert.equal(principal.unrestrictedModels,true);
const chat=new ChatService({chatDir:path.join(root,'chat'),dataDir:path.join(root,'files'),imageDir:path.join(root,'images'),codexBin:'/bin/false',codexWorkDir:root,serverAdministrator:principal.admin,allowedModels:principal.unrestrictedModels?null:new Set(['gpt-5.5']),quotaExhausted:!principal.unrestrictedModels,codexProfiles:{default:{id:'default',workDir:root}},allowedCodexProfiles:['default'],sendJson(){},readJsonBody(){}});
chat.runNext=()=>{};
assert.equal(chat.allowedModels,null);assert.equal(chat.quotaExhausted,false);assert.equal(chat.serverAdministrator,false);
for(const model of ['gpt-6.1-sol','gpt-6.1-terra','gpt-6-astra'])assert(chat.modelAllowed(model));
auth.setUserPolicy(device.device.userId,{codexProfiles:['default'],unrestrictedModels:false});assert.equal(auth.authenticateToken(device.token).unrestrictedModels,false,'explicit future admin revocation must remain possible');
const disabled=auth.read();disabled.devices[0].disabled=true;auth.write(disabled);
assert.equal(auth.authenticateToken(device.token),null);
chat.store.close();auth.store.db.close();
console.log('PASS new-user full model default, global fallback, ordinary-user isolation, explicit policy override and disabled-device enforcement');
